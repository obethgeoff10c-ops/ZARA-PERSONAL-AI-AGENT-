from __future__ import annotations

from collections.abc import Sequence

from alembic import op

revision: str = "0001"
down_revision: str | None = None
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

SCHEMAS = (
    "core",
    "integrations",
    "content",
    "memory",
    "graph",
    "agent",
    "events",
    "proactive",
    "work",
    "crm",
    "dev",
    "audit",
    "billing",
)

EXTENSIONS = (
    "pgcrypto",
    "pg_trgm",
    "vector",
    "btree_gin",
    "citext",
)


def upgrade() -> None:
    for extension in EXTENSIONS:
        op.execute(f'CREATE EXTENSION IF NOT EXISTS "{extension}"')

    for schema in SCHEMAS:
        op.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')

    # UUIDv7 is generated by the application (D-04). This helper lets later
    # migrations add a cheap CHECK that a value really is version 7.
    op.execute(
        """
        CREATE OR REPLACE FUNCTION core.is_uuid_v7(value uuid)
        RETURNS boolean
        LANGUAGE sql
        IMMUTABLE
        PARALLEL SAFE
        AS $$
            SELECT substr(value::text, 15, 1) = '7'
        $$;
        """
    )

    op.execute(
        """
        CREATE OR REPLACE FUNCTION core.set_updated_at()
        RETURNS trigger
        LANGUAGE plpgsql
        AS $$
        BEGIN
            NEW.updated_at = now();
            RETURN NEW;
        END;
        $$;
        """
    )


def downgrade() -> None:
    # Forward-only in production (02-DATABASE.md §4). This exists for dev resets.
    # ``core`` is retained because it holds alembic_version.
    op.execute("DROP FUNCTION IF EXISTS core.set_updated_at()")
    op.execute("DROP FUNCTION IF EXISTS core.is_uuid_v7(uuid)")
    for schema in reversed(SCHEMAS):
        if schema != "core":
            op.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
